test('successful integration adapters persist results without performing shop writes',async t=>{
  const dir=await mkdtemp(path.join(os.tmpdir(),'luvtora-sync-'));
  let calls=0;
  const service=await createService({dataDir:dir,integrations:{syncWoo:async()=>{calls++;return {products:[{id:1,name:'项链',sku:'N1',manageStock:true,stock:2}],orders:[],lastSync:'2026-10-13T00:00:00Z'};},generatePlan:async()=>({id:'plan-test',content:'待审核脚本',brief:'视频',createdAt:'2026-10-13T00:00:00Z',executed:false})}});
  t.after(async()=>{await new Promise(r=>service.server.close(r));await rm(dir,{recursive:true,force:true});});
  const html=await (await fetch(service.url)).text(),token=html.match(/name="luvtora-session" content="([^"]+)"/)[1];
  const post=async(endpoint,data)=>fetch(service.url+'/api/'+endpoint,{method:'POST',headers:{'x-luvtora-token':token,'Content-Type':'application/json'},body:JSON.stringify(data)});
  assert.equal((await post('woo/sync',{})).status,200);assert.equal(calls,1);
  assert.equal((await post('plans/generate',{brief:'视频'})).status,200);
  const state=await (await fetch(service.url+'/api/state',{headers:{'x-luvtora-token':token}})).json();
  assert.equal(state.products[0].name,'项链');assert.equal(state.metrics.lowStock,1);assert.equal(state.plans[0].executed,false);
});
